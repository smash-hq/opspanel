package gpu

import "testing"

const ascendSample = `
+-------------------------------------------------------------------------------------------+
| npu-smi 23.0.rc1                          Version: 23.0.rc1                                |
+---------------------------+-----------------+---------------------------------------------+
| NPU     Name              | Health          | Power(W)     Temp(C)         Hugepages-Usage(page) |
| Chip    Device            | Bus-Id          | AICore(%)    Memory-Usage(MB)                |
+---------------------------+-----------------+---------------------------------------------+
| 0       910B1             | OK              | 66.2         43                0     0      |
| 0       0                 | -               | 0            1024 / 32768                     |
+---------------------------+-----------------+---------------------------------------------+
| 1       910B1             | OK              | 65.1         44                0     0      |
| 1       0                 | -               | 12           2048 / 32768                     |
+---------------------------+-----------------+---------------------------------------------+
`

func TestParseAscend(t *testing.T) {
	devices := parseAscend(ascendSample)
	if len(devices) != 2 {
		t.Fatalf("期望 2 张卡，实际 %d：%+v", len(devices), devices)
	}

	d := devices[0]
	if d.Index != "0" || d.Name != "910B1" || d.Health != "OK" {
		t.Errorf("卡0 基础字段错误：%+v", d)
	}
	if d.PowerW != "66.2" || d.TempC != "43" {
		t.Errorf("卡0 功耗/温度错误：%+v", d)
	}
	if d.CoreUtil != "0" || d.MemUsedMB != "1024" || d.MemTotalMB != "32768" {
		t.Errorf("卡0 利用率/显存错误：%+v", d)
	}

	d = devices[1]
	if d.Index != "1" || d.PowerW != "65.1" || d.TempC != "44" {
		t.Errorf("卡1 基础字段错误：%+v", d)
	}
	if d.CoreUtil != "12" || d.MemUsedMB != "2048" || d.MemTotalMB != "32768" {
		t.Errorf("卡1 利用率/显存错误：%+v", d)
	}
}

func TestParseAscendGarbage(t *testing.T) {
	// 解析宽容：非表格输入不报错、不产出设备
	if devices := parseAscend("command not found\nrandom text"); len(devices) != 0 {
		t.Errorf("期望 0 张卡，实际 %d", len(devices))
	}
}

