func TestParseAscend910B(t *testing.T) {
	devices := parseAscend(ascend910BSample)
	if len(devices) != 8 {
		t.Fatalf("期望 8 张卡，实际 %d：%+v", len(devices), devices)
	}

	// 卡0：空闲 AICore，显存取 HBM（Memory-Usage 的 0/0 应被跳过）
	d := devices[0]
	if d.Index != "0" || d.Name != "910B2" || d.Health != "OK" {
		t.Errorf("卡0 基础字段错误：%+v", d)
	}
	if d.PowerW != "98.5" || d.TempC != "44" {
		t.Errorf("卡0 功耗/温度错误：%+v", d)
	}
	if d.CoreUtil != "0" || d.MemUsedMB != "25344" || d.MemTotalMB != "65536" {
		t.Errorf("卡0 利用率/HBM 显存错误：%+v", d)
	}

	// 卡4：AICore 36%，功耗 175.8W，HBM 接近满载
	d = devices[4]
	if d.PowerW != "175.8" || d.TempC != "50" || d.CoreUtil != "36" ||
		d.MemUsedMB != "64694" || d.MemTotalMB != "65536" {
		t.Errorf("卡4 字段错误：%+v", d)
	}

	// 卡5：AICore 67%
	if d = devices[5]; d.CoreUtil != "67" || d.MemUsedMB != "64692" {
		t.Errorf("卡5 字段错误：%+v", d)
	}

	// 卡7：无进程明细干扰
	if d = devices[7]; d.CoreUtil != "0" || d.MemUsedMB != "65199" || d.MemTotalMB != "65536" {
		t.Errorf("卡7 字段错误：%+v", d)
	}
}
